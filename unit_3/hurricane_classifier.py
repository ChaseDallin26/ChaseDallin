wind_speed = int(input ("what is the wind speed of the storm\n>"))

if wind_speed <=74:
    print("tropical storm")
elif wind_speed <=96:
    print ("category 1")
elif wind_speed <=111:
    print ("category 2")
elif wind_speed <=130:
    print ("category 3")
elif wind_speed <=157:
    print ("category 4")
elif wind_speed >= 157:
    print ("category 5")




